#!/usr/bin/env python3
"""Generate public app configuration; never read a private payment key."""
import argparse
import json
import plistlib
import re
from pathlib import Path
from urllib.parse import urlparse

p = argparse.ArgumentParser()
p.add_argument("--site-origin", required=True)
a = p.parse_args()
url = urlparse(a.site_origin)
if url.scheme != "https" or not url.netloc or url.path not in ("", "/") or url.query or url.fragment or url.username:
    raise SystemExit("Informe a origem HTTPS, sem caminho, senha, query ou fragmento.")
root = Path(__file__).resolve().parents[1]
config = json.loads((root / "website/commerce.config.json").read_text())
origin = a.site_origin.rstrip("/")
license = dict(environment=config["environment"], storeID=config["storeID"], productID=config["productID"],
               variantIDs=[plan["variantID"] for plan in config["plans"].values()],
               checkoutURL=origin + "/#assinatura", subscriptionURL=origin + "/api/license/subscription")
license.update(siteURL=origin, supportEmail=config.get("supportEmail", ""))
subdomain = config.get("storeSubdomain", "")
if re.fullmatch(r"[a-z0-9][a-z0-9-]*", subdomain):
    license["portalURL"] = "https://" + subdomain + ".lemonsqueezy.com/billing"
with (root / "Sources/BulkMaker/Resources/LicenseConfiguration.plist").open("wb") as file:
    plistlib.dump(license, file)
updates_path = root / "updates.json"
updates = json.loads(updates_path.read_text())
updates["feedURL"] = origin + "/appcast.xml"
updates_path.write_text(json.dumps(updates, indent=2) + "\n")
version = (root / "VERSION").read_text().strip()
feed_setting = updates["feedURL"].replace("//", "/$()/")
(root / "Xcode/Distribution.xcconfig").write_text(
    "// Public configuration only. Regenerated by scripts/configure-commerce.py.\n"
    + "CAROUSEL_FEED_URL = " + feed_setting + "\n"
    + "CAROUSEL_ED_PUBLIC_KEY = " + updates["publicEDKey"] + "\n"
    + "MARKETING_VERSION = " + version + "\n")
print("Configuração pública do app e endereço do appcast gerados. Nenhum segredo foi copiado.")
